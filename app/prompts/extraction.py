"""LLM prompt for feature extraction from a technical specification page.

The output shape (fields, types, what each field means) lives in the structured
output schema (app/schemas/extraction.py) — the prompt only explains the spec
conventions the schema cannot express: how to recognise a feature, how to read
the [TABLE:Tn]/[LINK:Ln] markers, and what counts as a field mapping.
"""

DETECT_FEATURE_PROMPT = """
Документ — техническое задание (ТЗ) на одну или несколько функциональностей сервиса.
Извлеки их в структуру по схеме ответа. Заполняй текстовые поля на русском,
сохраняя терминологию ТЗ; имена полей, таблиц, топиков и путей — как в документе.
Чего в документе нет — оставляй null или пустым списком, не додумывай.

## Что считать feature

- kafka_consumer — консьюмер Kafka-топика; обычно один на документ.
- rest_endpoint — REST-эндпоинт; обычно один на документ.
- scheduled_task — автоматическая задача по расписанию. В одном документе их
  может быть несколько: раздел вроде «Автоматические задачи» / «Регламентные
  задачи», где каждый подраздел имеет своё название, своё «Время запуска /
  Периодичность» и свою последовательность шагов. Каждый такой подраздел —
  отдельная feature со своим уникальным name (латинский snake_case по смыслу
  заголовка), display_name = заголовок подраздела дословно, schedule = формулировка
  расписания дословно. Раздел без явной пометки, но описывающий периодическую
  выборку из БД без входящего сообщения или HTTP-запроса, — тоже scheduled_task.
  У автозадачи input_tables и response_tables пустые.

## Таблицы параметров

Перед каждой таблицей документа стоит маркер [TABLE:Tn]; таблицы уже извлечены
дословно, ты только относишь их к секциям по id.
- input_tables — таблицы раздела «Входные параметры» (для Kafka — структура
  входящего сообщения). Если вход разбит на несколько таблиц (Header, query,
  тело) — перечисли все в порядке документа.
- response_tables — таблицы раздела «Выходные параметры», каждая со своим
  status_codes из заголовка над ней («HTTP 200 OK» → "200", «HTTP 400, 404, 500»
  → "400, 404, 500"). Перечисли и успешные, и ошибочные ответы.
Таблица может быть и в response_tables, и в mapping_table_ids шага, который
формирует этот ответ.

## Шаги логики

logic_steps — плоский список шагов в порядке документа; вложенность задаётся
номером: «2.3» — подшаг шага «2», «2.3.1» — подшаг «2.3». Сохраняй гранулярность
документа: одна операция = один шаг; UPDATE таблицы A и затем INSERT в таблицу B —
два шага. Текст шага копируй дословно. Исключение — шаг с маппингом полей
(has_detailed_mapping = true): его text — краткое описание действия
(«Сформировать сообщение LoanAddRq и отправить в очередь»), без перечисления
полей, они берутся из таблицы.

Маппинг полей — это структурное заполнение сообщения или строки БД: таблица с
именами полей и их типом/источником, перечисление «поле = значение» для
INSERT/UPDATE, список полей объекта с источниками значений. Признак: две и более
пары «поле → источник/значение». У такого шага has_detailed_mapping = true,
mapping_table_ids = id его таблиц, message_type = имя целевого сообщения/таблицы.
Если маппинг разбит по подшагам (7.1 — поле id, 7.2 — поле name), помечай
родительский шаг.

Не маппинг, а справочная таблица — её место в reference_tables шага (дословно,
headers + rows): соответствие значений enum/кодов → действий, справочник кодов
ошибок или статусов, матрица прав/условий, соответствие между сущностями.
В такой таблице нет имён полей одной структуры и колонки «Тип данных».
Сомневаешься — выбирай reference_tables. Одна таблица — либо маппинг, либо
справочник, не оба сразу.

## Зависимости

used_dependencies — всё, с чем feature взаимодействует или на что ссылается:
- external_api — REST-вызов другого сервиса: name = путь, method, service_name, path;
- db_table — таблица БД, в которую пишет или из которой читает;
- kafka_topic — топик, в который публикует (отправка в топик — это kafka_topic,
  не external_api);
- cache — используемый кеш;
- external_doc — любой другой документ, на который ссылается шаг: регламент,
  правила формирования, справочник, спецификация маппинга, страница параметров
  конфигурации. Если ссылку нельзя уверенно отнести к исполняемой сущности —
  это external_doc: лишний external_doc лучше потерянной ссылки.

Ссылки на другие страницы помечены в тексте маркером [LINK:Ln] сразу после текста
ссылки. Для каждой зависимости, упомянутой со ссылкой, заполни link_ids этими id
(все, если одна зависимость описана на нескольких страницах). Каждый маркер
[LINK:Ln] документа должен попасть в link_ids хотя бы одной зависимости — ссылка
в ТЗ и есть зависимость; несколько параметров конфигурации с одной страницы
ссылаются на один и тот же маркер. Одна ссылка — одна запись: страница, уже
учтённая как external_api/db_table/kafka_topic/cache, не дублируется как
external_doc.

Для external_doc: name — название документа из текста ссылки; в каждом шаге, где
документ упоминается, продублируй это же name в external_doc_refs шага (ключ связи,
совпадение посимвольное). Зависимости хранятся на уровне feature: если несколько
scheduled_task используют одну таблицу, она указывается у каждой.
""".strip()
