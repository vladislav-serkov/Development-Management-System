DETECT_FEATURE_PROMPT = """
<task>
Это техническое задание (ТЗ). Документ описывает ОДНУ ИЛИ НЕСКОЛЬКО функциональностей (features).

Возможные типы feature:
- kafka_consumer — Kafka-консьюмер. Как правило ровно ОДИН на документ.
- rest_endpoint — REST-эндпоинт. Как правило ровно ОДИН на документ.
- scheduled_task — автоматическая задача по расписанию (автозадача, cron-job).
  В одном документе может быть НЕСКОЛЬКО таких задач (разделы «Автоматические задачи»,
  «Scheduled tasks» и т.п., где под одним заголовком перечислены независимые задачи,
  каждая со своим расписанием запуска).

Верни список features. Обычно это 1 элемент (для kafka/rest), но для scheduled_task
— столько, сколько независимых автозадач описано в документе.

Маркеры нескольких scheduled_task в одном документе:
- заголовок раздела вроде «Автоматические задачи», «Регламентные задачи»;
- далее идёт нумерованный/маркированный список подразделов, каждый со своим
  заголовком-названием задачи и собственным блоком «Время запуска / Периодичность»
  (например «каждый час», «раз в сутки в 19:00 МСК», «ежедневно», cron-выражение);
- каждый подраздел описывает независимую последовательность шагов.
Каждый такой подраздел = отдельный элемент в списке features.

Если тип задачи не помечен явно, но раздел описывает выборку из БД по периодическому
триггеру без входящего сообщения/HTTP-запроса — это scheduled_task.
</task>

<output_fields_per_feature>
- name: КОРОТКИЙ ЛАТИНСКИЙ ИДЕНТИФИКАТОР (snake_case):
  • Для Kafka — полное имя топика (например pay-later.flp.rbo-adapter.product.return.queue).
  • Для REST — METHOD /path (например 'GET /v1/credit-line').
  • Для scheduled_task — латинский snake_case slug, собранный по смыслу заголовка
    автозадачи, например 'send_limit_check_request', 'retry_limits_to_krab',
    'retry_installment_events_to_krab'. Должен быть уникален среди features документа.
- display_name: ОРИГИНАЛЬНОЕ русское название из документа ДОСЛОВНО.
  • Для scheduled_task — ОБЯЗАТЕЛЬНО: точный заголовок раздела автозадачи
    (например «Отправка запроса на проверку актуальности лимита»,
    «Повторная отправка лимитов клиентов в КРАБ»).
  • Для kafka_consumer / rest_endpoint — null (UI покажет `name`).
- type: kafka_consumer | rest_endpoint | scheduled_task
- summary: краткое описание на русском
- method:
  • Для REST — GET/POST/PUT/DELETE.
  • Для Kafka — CONSUMER.
  • Для scheduled_task — SCHEDULED.
- endpoint:
  • Для REST — путь эндпоинта.
  • Для Kafka — имя топика.
  • Для scheduled_task — null.
- schedule: расписание триггера ДОСЛОВНО из документа (на русском).
  • Для scheduled_task — ОБЯЗАТЕЛЬНО: «Ежедневно в 19:00 МСК», «Каждый час»,
    «Раз в сутки», «cron: 0 19 * * *» и т.п. Копируй формулировку из раздела
    «Время запуска» / «Периодичность» / тела задачи.
  • Для kafka_consumer / rest_endpoint — null.
- dependencies: список имён зависимостей (строки)

- structured_logic:
  - input_tables: таблицы раздела «Входные параметры» — список объектов, у каждого
    заполни ТОЛЬКО table_id: id маркера [TABLE:Tn], стоящего в документе перед таблицей.
    Если вход описан несколькими таблицами (отдельно Header, отдельно query, отдельно
    тело) — перечисли ВСЕ, в порядке документа.
    Для kafka_consumer — таблицы структуры входящего сообщения.
    Поля caption/location/columns/fields НЕ заполняй — таблица будет извлечена кодом
    дословно (см. правило 6 про документы без маркеров).

  - response_tables: таблицы раздела «Выходные параметры» — список объектов, у каждого
    заполни ТОЛЬКО table_id и status_codes.
    status_codes — HTTP-статусы из заголовка над таблицей дословно:
    «HTTP 200 OK» → "200"; «HTTP 400, 404, 500» → "400, 404, 500".
    Перечисли ВСЕ таблицы ответов — и успешные (2xx), и ошибочные (4xx/5xx),
    в порядке документа. Для kafka_consumer / scheduled_task — пустой список.
    ВАЖНО: response_tables НЕ отменяет mapping_table_ids у шагов. Если шаг логики
    формирует тело ответа по этой же таблице — укажи её id И в response_tables,
    И в mapping_table_ids этого шага.

  - logic_steps: шаги обработки с полями
    number (нумерация '1', '1.1', '1.1.2'),
    text (описание шага на русском — см. секцию rules),
    has_detailed_mapping (см. секцию rules),
    reference_tables (справочные/lookup-таблицы шага — см. секцию rules),
    external_doc_refs (список имён внешних документов, упомянутых в этом шаге — см. секцию rules),
    children (вложенные подшаги)

  - used_dependencies: список зависимостей с полями
    type (db_table/external_api/cache/kafka_topic/external_doc),
    name (имя таблицы/кеша/топика Kafka; для external_api — path эндпоинта; для external_doc — название документа из ссылки),
    description (для чего используется, на русском),
    method (для external_api: HTTP метод, null для остальных),
    service_name (для external_api: имя целевого сервиса, null для остальных),
    path (для external_api: путь эндпоинта, null для остальных)
</output_fields_per_feature>

<rules>
1. ЯЗЫК: все текстовые поля (description, text, summary) заполняй
   НА РУССКОМ ЯЗЫКЕ, сохраняя терминологию из оригинального ТЗ. Имена параметров и ключи — на латинице.

2. ОТСУТСТВУЮЩАЯ ИНФОРМАЦИЯ: если информация отсутствует в документе — возвращай null или пустой список.
   Никогда не выдумывай и не додумывай значения. Лучше вернуть null, чем угадать неправильно.

3. ЗАВИСИМОСТИ: external_api — только REST-вызовы к внешним сервисам.
   Отправку сообщений в Kafka-топики указывай как kafka_topic.

3a. SCHEDULED_TASK — особенности:
   - input_tables — пустой список []. Автозадача не принимает параметры, её триггер — расписание.
   - response_tables — пустой список [].
   - logic_steps — описывают полный цикл работы задачи (выборка из БД → обработка →
     вызов внешнего API/отправка в очередь → обновление статусов).
   - Каждая scheduled_task в списке features должна иметь УНИКАЛЬНЫЙ `name` (slug).
   - Общие зависимости (одна и та же БД-таблица, один и тот же внешний endpoint)
     у нескольких scheduled_task в документе дублировать в used_dependencies ЭТОЙ
     feature — зависимости хранятся на уровне feature, для каждой повторяй своим списком.

4. ВЛОЖЕННОСТЬ: используй вложенность в logic_steps для отражения структуры документа.
   НИКОГДА не сливай несколько операций с разными целевыми таблицами или сообщениями в один шаг.
   Если документ описывает последовательно: UPDATE таблицы A, затем INSERT в таблицу B —
   это ДВА отдельных подшага, каждый со своим has_detailed_mapping.
   Сохраняй гранулярность документа: одна операция = один шаг.

5. ТЕКСТ ШАГОВ (logic_steps.text):
   - Обычные шаги (has_detailed_mapping: false): копируй ДОСЛОВНО текст из документа, не перефразируй.
   - Шаги с маппингом (has_detailed_mapping: true): пиши ТОЛЬКО краткое описание действия
     (например «Сформировать XML-сообщение с типом LoanAddRq и отправить в очередь»),
     БЕЗ перечисления полей — поля извлекаются кодом из таблиц по mapping_table_ids.

6. ДОКУМЕНТЫ БЕЗ МАРКЕРОВ [TABLE:Tn] (редкий случай — legacy-импорт): если маркеров
   в документе нет, заполни input_tables / response_tables / mapping_tables шагов
   inline сам:
   - columns: список объектов {header} — заголовки колонок таблицы ДОСЛОВНО,
     в порядке слева-направо, БЕЗ колонки с именем поля (она отражается в name);
   - fields: строки таблицы как дерево — name (имя поля из колонки-имени),
     cells (значения остальных ячеек ДОСЛОВНО, по порядку columns; пустая ячейка — ""),
     children (вложенные поля).
   Ничего не перефразируй и не синтезируй — только дословный перенос таблицы.
   Если структура описана не таблицей, а списком/прозой — columns: [{header: "Тип"},
   {header: "Описание"}] и разложи описание по этим ячейкам.

7. КРИТЕРИЙ has_detailed_mapping — это СТРУКТУРНЫЙ маппинг полей СООБЩЕНИЯ/СТРОКИ БД.
   Установи true ТОЛЬКО если шаг содержит ЛЮБОЕ из:
   - Таблицу маппинга XML/JSON полей/элементов сообщения (колонки содержат ИМЕНА ПОЛЕЙ
     латиницей/CamelCase и, как правило, ТИП данных + источник/описание)
   - Перечисление полей для INSERT/UPDATE записи в БД-таблицу (например: id = ..., name = ..., status = ...)
   - Список полей для формирования объекта/структуры с указанием источников значений
   - Ссылку на таблицу маппинга в другом месте документа (например «заполнить согласно таблице N»)
   - Таблицу в документе рядом с шагом, содержащую колонки с именами полей, типами или источниками значений —
     даже если шаг явно не говорит «заполнить поля», наличие такой таблицы означает маппинг
   Общий признак: шаг содержит 2+ пар «поле = значение/источник» в ЛЮБОМ формате —
   таблица, список, проза, подшаги с отдельными полями.

   ПОДШАГИ С ПОЛЯМИ: если маппинг разбит по подшагам (например 7.1 → поле id, 7.2 → поле name),
   пометь РОДИТЕЛЬСКИЙ шаг как has_detailed_mapping: true (и mapping_table_ids на нём же),
   а подшаги включи как children с has_detailed_mapping: false.

   НЕ ЯВЛЯЕТСЯ field mapping (has_detailed_mapping ДОЛЖЕН быть false, таблица идёт в reference_tables,
   см. правило 7a):
   - Таблица соответствия значений enum/кодов (например «$.type=INITIAL_PAYMENT → APPLICATION+CREDIT+PAYOFF»)
     — это lookup/справочник значений, а не поля структуры.
   - Справочник кодов ошибок, статусов, причин.
   - Матрица прав, ролей, условий/флагов.
   - Таблица «соответствие A ↔ B» между доменными сущностями (не полями одного сообщения).
   Признак reference-таблицы: строки описывают НЕ поля одной целевой структуры,
   а соответствия/правила между разными значениями. В колонках нет имён полей,
   нет колонки «Тип данных» — вместо неё перечисление значений/действий/количеств.

   Если сомневаешься между field mapping и reference table — склоняйся к reference_tables.
   Лучше сохранить таблицу дословно в reference_tables, чем засорить маппинг таблицей соответствий.

7b. МАРКЕРЫ ТАБЛИЦ [TABLE:Tn]. Если в документе перед таблицами стоят маркеры вида
   [TABLE:T3] — таблицы уже извлечены кодом дословно, и для шагов с
   has_detailed_mapping=true ты НЕ должен переписывать поля. Вместо этого:
   - в `mapping_table_ids` шага укажи id маркеров таблиц с маппингом полей
     этого шага (например ["T3"]);
   - заполни `message_type` шага — имя целевого сообщения/таблицы из текста;
   - `mapping_tables` шага оставь пустым — таблицы будут извлечены кодом дословно.
   Правило 7 (что является field mapping, а что reference-таблица) действует
   без изменений: reference-таблицы по-прежнему копируй в reference_tables
   дословно и НЕ указывай их id в mapping_table_ids.
   Если маркеров в документе нет — оставляй mapping_table_ids пустым списком.

7a. REFERENCE_TABLES — для каждого шага извлеки все reference-таблицы из секции
   «НЕ ЯВЛЯЕТСЯ field mapping» выше в поле `reference_tables` как список объектов:
   - caption: заголовок таблицы, если есть в документе (иначе null)
   - headers: список строк — заголовки колонок ДОСЛОВНО из таблицы, в порядке слева-направо
   - rows: список строк таблицы; каждая строка — список ячеек-строк той же длины, что headers.
     Содержимое ячеек копируй ДОСЛОВНО из документа, на русском. Пустые ячейки — пустая строка "".
   Если reference-таблиц нет — оставь пустой список [].
   НИКОГДА не дублируй одну и ту же таблицу одновременно в reference_tables и в field mapping.

8. ВНЕШНИЕ ДОКУМЕНТЫ И ДРУГИЕ ССЫЛКИ НА АРТЕФАКТЫ

   Если в тексте шага встречается ссылка на внешний артефакт (документ,
   спецификацию, регламент, справочник, схему, описание, swagger, DDL) —
   он ОБЯЗАН попасть в `used_dependencies`. Пропускать ссылки нельзя.
   Тип выбирается по приоритету:

   (1) Если артефакт описывает ИСПОЛНЯЕМУЮ СУЩНОСТЬ, с которой фича
   взаимодействует в рантайме — используй соответствующий тип:
     - swagger / описание REST-эндпоинта, который фича вызывает → external_api
       (name = path эндпоинта, method + service_name + path заполнены)
     - DDL / схема таблицы, в которую фича пишет или из которой читает → db_table
     - схема сообщения топика Kafka, в который фича публикует / из которого
       читает → kafka_topic
     - спецификация кеша, который фича использует → cache

   (2) ИНАЧЕ (артефакт не описывает исполняемую сущность, а содержит
   правила / регламент / справочник / бизнес-логику / процесс /
   спецификацию маппинга) → external_doc.

   Типовые формулировки-маркеры external_doc:
     - «правила формирования JSON для Краб»
     - «регламент обработки по процессу X»
     - «согласно описанию в документе Y»
     - «справочник кодов ошибок»
     - «спецификация маппинга полей …»

   ПРАВИЛО ПО УМОЛЧАНИЮ: если в шаге есть ссылка и ты НЕ можешь однозначно
   отнести её к external_api / db_table / kafka_topic / cache — ставь
   external_doc. Лучше лишний external_doc, чем потерянная ссылка.

   МАРКЕРЫ ССЫЛОК [LINK:Ln]. Каждая ссылка на другую страницу помечена в
   документе маркером сразу после текста ссылки, например:
     «Произвести поиск записей таблицы product_date [LINK:L5]»
     «Произвести вызов метода [flp-tariff] POST /v1/schedule [LINK:L2]»

   Для КАЖДОЙ записи в used_dependencies (ЛЮБОГО типа, не только external_doc),
   которая упомянута в тексте со ссылкой — заполни `link_ids` списком id этих
   маркеров (например ["L5"]). Если зависимость упомянута со ссылками на разные
   страницы (например таблица minimal_required_payment описана и в [flp-order] DB,
   и в [flp-rbo-adapter] DB) — перечисли ВСЕ соответствующие id.
   Если артефакт упомянут без ссылки — оставь link_ids пустым списком.
   Поле `source_doc_title` в документе с маркерами НЕ заполняй (оставь null).

   ПОКРЫТИЕ ССЫЛОК — ЖЁСТКОЕ ТРЕБОВАНИЕ: КАЖДЫЙ маркер [LINK:Ln], встречающийся
   в документе, ОБЯЗАН быть указан в `link_ids` хотя бы одной записи
   used_dependencies. Ссылка в документе = зависимость. Перед завершением
   пройдись по всем маркерам документа и проверь, что ни один не потерян.
   Это относится в том числе к ссылкам на параметры конфигурации сервиса
   («Коэффициент МОП», «Количество дней до перевода на штрафной тариф») —
   их страница конфигурации является external_doc, а несколько параметров
   с одной и той же страницы могут ссылаться на один и тот же [LINK:Ln].

   ОДНА ССЫЛКА = ОДНА ЗАПИСЬ. Правила (1) и (2) взаимоисключающие:
   если ссылка уже классифицирована как external_api / db_table /
   kafka_topic / cache, НЕ добавляй её же второй раз как external_doc.
   Типовая ошибка: страница «Описание метода getX» породила и
   external_api (path /api/getX), и external_doc («getX — Получение …») —
   это дубль, external_doc здесь создавать НЕЛЬЗЯ.

   Для external_doc выполни:
   а) Добавь запись в `used_dependencies` с type="external_doc", name=<точное
      название документа из текста ссылки>, description=<кратко на русском,
      для чего используется>. Поля method/service_name/path оставь null.

   б) В том шаге (logic_step), где встречается упоминание, заполни
      `external_doc_refs` списком имён этих документов. Имя в
      `external_doc_refs` ДОЛЖНО посимвольно совпадать с `name` в
      `used_dependencies` — это ключ связи.

   в) Если один документ упомянут в нескольких шагах — в `used_dependencies`
      он появляется один раз, но в `external_doc_refs` прописывается в
      каждом шаге, где упоминается.

</rules>
""".strip()
